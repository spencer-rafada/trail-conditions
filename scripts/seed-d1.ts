// Hand-run seed for the local D1 database (M3): loads data/trails.json into
// trails + trail_points.
//
//   pnpm tsx scripts/seed-d1.ts
//   cd apps/worker && pnpm exec wrangler d1 execute trail-conditions --local \
//     --file .wrangler/seed.sql
//
// Local only — never pass --remote. The generated SQL lands under
// apps/worker/.wrangler/ (gitignored) and reseeds idempotently (deletes the
// two tables first).
//
// Column mapping (trails.json has no exact §8 columns):
// - trails.name      := trails.json `system` (the display name lives there;
//                       nothing in the data names a separate trail system)
// - trails.system    := NULL
// - trails.osm_ref   := the `osm_refs` string as-is
// - trail_points.id  := `<trail_id>#<label lowercased>` (minted; the data has
//                       no per-point id)
// - sand/clay/hydgrp := soil.sandPct / soil.clayPct / soil.hydrologicGroup
// - rock             := soil.fragGt10Pct + soil.frag3to10Pct (NULL only when
//                       both are null), matching how TAU uses rock fragments
// - NULL soil values are preserved (120 points have none)

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

interface TrailPoint {
  label: string;
  lat: number;
  lon: number;
  elev_m: number | null;
  soil: {
    sandPct: number | null;
    clayPct: number | null;
    fragGt10Pct: number | null;
    frag3to10Pct: number | null;
    hydrologicGroup: string | null;
  };
  drainage: string | null;
  cell_id: string;
}

interface Trail {
  id: string;
  system: string;
  county: string | null;
  osm_refs: string;
  tau_base_h: number;
  tau_mult: number;
  points: TrailPoint[];
}

const root = fileURLToPath(new URL("..", import.meta.url));
const { trails } = JSON.parse(
  readFileSync(path.join(root, "data/trails.json"), "utf8"),
) as { trails: Trail[] };

const sqlText = (v: string | null): string =>
  v === null ? "NULL" : `'${v.replaceAll("'", "''")}'`;
const sqlNum = (v: number | null): string => (v === null ? "NULL" : String(v));

const lines: string[] = [
  "-- Generated by scripts/seed-d1.ts from data/trails.json. Do not edit.",
  "DELETE FROM trail_points;",
  "DELETE FROM trails;",
];

let pointCount = 0;
for (const t of trails) {
  lines.push(
    "INSERT INTO trails (id, name, system, county, osm_ref, tau_base_h, tau_mult, reports_used) VALUES (" +
      [
        sqlText(t.id),
        sqlText(t.system), // display name lives in `system` in trails.json
        "NULL",
        sqlText(t.county),
        sqlText(t.osm_refs),
        sqlNum(t.tau_base_h),
        sqlNum(t.tau_mult),
        "0",
      ].join(", ") +
      ");",
  );
  for (const p of t.points) {
    pointCount += 1;
    const rock =
      p.soil.fragGt10Pct === null && p.soil.frag3to10Pct === null
        ? null
        : (p.soil.fragGt10Pct ?? 0) + (p.soil.frag3to10Pct ?? 0);
    lines.push(
      "INSERT INTO trail_points (id, trail_id, label, lat, lon, elev_m, sand, clay, rock, hydgrp, drainage, cell_id) VALUES (" +
        [
          sqlText(`${t.id}#${p.label.toLowerCase()}`),
          sqlText(t.id),
          sqlText(p.label),
          sqlNum(p.lat),
          sqlNum(p.lon),
          sqlNum(p.elev_m),
          sqlNum(p.soil.sandPct),
          sqlNum(p.soil.clayPct),
          sqlNum(rock),
          sqlText(p.soil.hydrologicGroup),
          sqlText(p.drainage),
          sqlText(p.cell_id),
        ].join(", ") +
        ");",
    );
  }
}

const outDir = path.join(root, "apps/worker/.wrangler");
mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, "seed.sql");
writeFileSync(outFile, lines.join("\n") + "\n");

console.log(`Wrote ${trails.length} trails / ${pointCount} points to ${outFile}`);
console.log(
  "Apply with: cd apps/worker && pnpm exec wrangler d1 execute trail-conditions --local --file .wrangler/seed.sql",
);
